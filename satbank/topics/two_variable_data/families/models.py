from ...two_variable_data import charts
from ..common import count_word, listing, num_str, pick, q

__all__ = ["best_model", "growth_compare", "invest_compare", "nonlinear_table"]

SUP = str.maketrans("0123456789x", "⁰¹²³⁴⁵⁶⁷⁸⁹ˣ")


def _term(c, body, places=None, first=False):
    c = q(c)
    if c == 0:
        return ""
    mag = num_str(abs(c), places)
    if body and abs(c) == 1:
        mag = ""
    head = ("−" if c < 0 else "") if first else (" − " if c < 0 else " + ")
    return f"{head}{mag}{body}"


_Q = __import__("re").compile(r"([+−-]?)([\d.]*)(x²|x|)")


def _read_quad(text: str) -> tuple:
    """A printed quadratic as (a, b, c), read back from the string itself."""
    body = text.split("=", 1)[1].replace(" ", "").replace(",", "")
    a = b = c = Q(0)
    i = 0
    while i < len(body):
        m = _Q.match(body, i)
        if m is None or m.end() == i:
            raise ItemError(f"cannot read back {text!r}")
        sign, digits, tail = m.groups()
        v = q(digits) if digits else Q(1)
        if sign in ("-", "−"):
            v = -v
        if tail == "x²":
            a += v
        elif tail == "x":
            b += v
        else:
            c += v
        i = m.end()
    return a, b, c


def quad_text(a, b, c, var="x", *, lhs="y", places=None) -> str:
    """A quadratic as the page prints one: y = 2x² − 11x + 20."""
    if q(a) == 0:
        raise ItemError("that is not a quadratic model")
    out = _term(a, f"{var}²", places, first=True)
    out += _term(b, var, places)
    out += _term(c, "", places)
    return f"{lhs} = {out}"


# --------------------------------------------------- which curve fits the dots

MODEL_CTX = [
    dict(intro="",
         ask="Of the following, which is the best model for the data in the scatterplot?",
         title="", xlabel="x", ylabel="y", places=None,
         xstep=1, xlabel_every=1, ystep=2, ylabel_every=1, x_lo=0, dx=Q(1, 2), n=12,
         arange=(1, 3), hrange=(2, 4), krange=(3, 8), res=Q(1, 2)),
    dict(intro="The scatterplot shows the amount of electric energy generated, in "
               "millions of megawatt-hours, by nuclear sources over a {n}-year period.",
         ask="Of the following equations, which best models the data in the "
             "scatterplot?",
         title="Electric Energy Generated by Nuclear Sources", xlabel="Time (years)",
         ylabel="Energy (million megawatt-hours)", places=None,
         xstep=2, xlabel_every=1, ystep=20, ylabel_every=1, x_lo=1, dx=1, n=10,
         arange=None, res=4),
]


def best_model(rng: random.Random, seed: int, *, ctx=None, a=None, b=None, c=None,
               b2=None, c2=None, xs=None, jitter=None, wrongs=None) -> Item:
    """A parabola of points, and the four quadratics one of which drew it."""
    d = MODEL_CTX[rng.randrange(len(MODEL_CTX))] if ctx is None else MODEL_CTX[ctx]
    if a is None:
        a = Q(rng.randint(*d["arange"])) if d["arange"] else Q(rng.randint(-24, -12), 10)
    a = q(a)
    if a == 0:
        raise ItemError("that is not a quadratic model")
    if b is None:
        h = Q(rng.randint(*d["hrange"])) if d.get("hrange") else Q(rng.randint(40, 70), 10)
        b = -2 * a * h
    b = q(b)
    if c is None:
        c = Q(rng.randint(*d["krange"])) if d.get("krange") else Q(rng.randint(700, 780))
    c = q(c)
    if c == 0:
        raise ItemError("a model through the origin cannot show its intercept")
    n = d["n"]
    xs = [q(d["x_lo"]) + q(d["dx"]) * i for i in range(n)] if xs is None else list(map(q, xs))
    f = lambda t: a * t * t + b * t + c
    jitter = q(jitter) if jitter is not None else q(d["res"]) / 4
    pts = [(x, f(x) + jitter * rng.choice((-1, 0, 0, 1))) for x in xs]

    key = quad_text(a, b, c, places=d["places"])
    pool = {
        "c_sign": ("gave the constant term the wrong sign", quad_text(a, b, -c, places=d["places"])),
        "a_sign": ("opened the parabola the wrong way",
                   quad_text(-a, b, c, places=d["places"])),
        "ac_sign": ("opened the parabola the wrong way and flipped the constant term",
                    quad_text(-a, b, -c, places=d["places"])),
        "bc_sign": ("moved the vertex to the wrong side and flipped the constant term",
                    quad_text(a, -b, -c, places=d["places"])),
        "ab_sign": ("opened the parabola the wrong way and moved the vertex to the "
                    "wrong side", quad_text(-a, -b, c, places=d["places"])),
        "alt": ("put the vertex in the wrong place",
                quad_text(a, b2, c2, places=d["places"])
                if b2 is not None and c2 is not None else None),
        "alt_c_sign": ("put the vertex in the wrong place and flipped the constant term",
                       quad_text(a, b2, -q(c2), places=d["places"])
                       if b2 is not None and c2 is not None else None),
    }
    order = ["c_sign", "a_sign", "ac_sign", "bc_sign", "ab_sign", "alt", "alt_c_sign"]
    mistakes = pick(pool, order, wrongs)
    ys = [p[1] for p in pts]
    spread = max(ys) - min(ys)
    for miss in mistakes:
        aa, bb, cc = _read_quad(miss.value)
        if max(abs(aa * x * x + bb * x + cc - y) for x, y in pts) < spread / 4:
            raise ItemError(f"the model {miss.value!r} is too close to the data to be "
                            f"wrong")
    choices, reasons, letter = assemble_text(key, mistakes, rng)

    step = q(d["ystep"])
    lo, hi = min(ys), max(ys)
    y0 = (lo // step - 1) * step
    y1 = (hi // step + 1 + (1 if hi % step else 0)) * step
    if lo >= 0 and y0 < 0:
        y0 = Q(0)
    fig = charts.scatter(pts, x0=q(d["x_lo"]) - q(d["dx"]), x1=xs[-1] + q(d["dx"]),
                         y0=y0, y1=y1, xstep=d["xstep"], ystep=step,
                         xlabel_every=d["xlabel_every"], ylabel_every=d["ylabel_every"],
                         xlabel=d["xlabel"], ylabel=d["ylabel"], title=d["title"])
    P = dict(kind="tvdata.best_model", a=str(a), b=str(b), c=str(c),
             xs=[str(x) for x in xs], ys=[str(v) for v in ys], texts=list(choices))
    stem = f"{d['intro'].format(n=count_word(n))} {d['ask']}".strip()
    return Item("tvdata.best_model", "choosing a model", "easy", seed, stem, "mcq",
                E(0), letter,
                f"The dots meet the vertical axis near {num_str(c)} and turn at "
                f"x = {num_str(-b / (2 * a))}.",
                choices, reasons, list(choices), figure=fig, params=P)


# ------------------------------------------ an exponential against a line

GROWTH_CTX = [
    dict(intro="", var="x", base=(2, 3), mrange=(2, 5), krange=(0, 6)),
    dict(intro="", var="x", base=(2, 2), mrange=(3, 9), krange=(0, 9)),
]


def _pattern(base, m, k):
    """'less', 'greater' or 'cross' for a^x against mx + k on x > 0.

    The two graphs may touch without crossing -- 2ˣ and 2x + 2 meet at x = 3 --
    so a point where they are equal is dropped rather than counted as a change
    of side.
    """
    signs = []
    for i in range(1, 2_001):
        x = Q(i, 40)
        lhs = float(base) ** float(x)
        rhs = float(m * x + k)
        if lhs != rhs:
            signs.append(lhs > rhs)
    if not signs:
        return None
    if not any(signs):
        return "less"
    if all(signs):
        return "greater"
    flips = sum(1 for a, b in zip(signs, signs[1:]) if a != b)
    return "cross" if flips == 1 and not signs[0] else None


def growth_compare(rng: random.Random, seed: int, *, base=None, m=None, k=None) -> Item:
    """Does an exponential stay under a line, stay over it, or cross it?"""
    d = GROWTH_CTX[rng.randrange(len(GROWTH_CTX))]
    base = int(base if base is not None else rng.randint(*d["base"]))
    m = q(m) if m is not None else Q(rng.randint(*d["mrange"]))
    k = q(k) if k is not None else Q(rng.randint(*d["krange"]))
    if base < 2 or m <= 0:
        raise ItemError("this stem compares a growing exponential with a rising line")
    shape = _pattern(base, m, k)
    if shape is None:
        raise ItemError("the two graphs meet in a way these four sentences cannot "
                        "describe")
    var = d["var"]
    exp = f"{base}{var.translate(SUP)}"
    line = f"{num_str(m)}{var} + {num_str(k)}" if k else f"{num_str(m)}{var}"
    S = {
        "less": f"For all {var} > 0, it is true that {exp} < {line}.",
        "greater": f"For all {var} > 0, it is true that {exp} > {line}.",
        "cross": (f"There is a constant c such that if 0 < {var} < c, then {exp} < "
                  f"{line}, but if {var} > c, then {exp} > {line}."),
        "cross_back": (f"There is a constant c such that if 0 < {var} < c, then {exp} > "
                       f"{line}, but if {var} > c, then {exp} < {line}."),
    }
    why = {
        "less": f"tried a small {var} only, where the line is above the exponential",
        "greater": f"tried a large {var} only, where the exponential is above the line",
        "cross": f"has the exponential overtaking the line, which happens only when the "
                 f"line starts above it",
        "cross_back": "has the line overtaking the exponential, which a line never does",
    }
    key = S[shape]
    wrong = [Mis(why[s], S[s]) for s in ("less", "greater", "cross", "cross_back")
             if s != shape]
    choices, reasons, letter = assemble_text(key, wrong, rng)
    P = dict(kind="tvdata.growth_compare", base=base, m=str(m), k=str(k),
             var=var, texts=list(choices))
    stem = (f"Which of the following is true about the values of {exp} and {line} for "
            f"{var} > 0?")
    return Item("tvdata.growth_compare", "comparing models", "medium", seed, stem,
                "mcq", E(0), letter,
                f"At {var} = 1 the values are {base} and {num_str(m + k)}, and an "
                f"exponential eventually passes any line.",
                choices, reasons, list(choices), params=P)


# ------------------------------------------ compound interest against a fee

INVEST_CTX = [
    dict(intro="Two investments were made as shown in the table. The interest in Account "
               "A is compounded once per year.",
         ask="Which of the following is true about the investments?",
         names=("Account A", "Account B"), head=("Amount invested", "Balance increase")),
    dict(intro="Two accounts were opened as shown in the table. The interest in Account "
               "A is compounded once per year, and no money is added to or taken from "
               "either account.",
         ask="Which of the following is true about the two accounts?",
         names=("Account A", "Account B"), head=("Amount invested", "Balance increase")),
]


def invest_compare(rng: random.Random, seed: int, *, ctx=None, pa=None, rate=None,
                   pb=None, fee=None) -> Item:
    """Compound interest against a fixed amount per year."""
    d = INVEST_CTX[rng.randrange(len(INVEST_CTX))] if ctx is None else INVEST_CTX[ctx]
    pa = int(pa if pa is not None else rng.randrange(200, 2_100, 100))
    pb = int(pb if pb is not None else rng.randrange(500, 3_100, 100))
    rate = q(rate) if rate is not None else Q(rng.randint(2, 9), 100)
    fee = q(fee) if fee is not None else Q(rng.randrange(10, 120, 5))
    first = q(pa) * rate
    if first == fee:
        raise ItemError("the two accounts earn the same in the first year")
    if first.denominator != 1 or fee.denominator != 1:
        raise ItemError("these balances are not whole numbers of dollars")
    A, B = d["names"]
    S = {
        "always_more": f"{A} always earns more money per year than {B}.",
        "always_less": f"{A} always earns less money per year than {B}.",
        "more_then_less": f"{A} earns more money per year than {B} at first but "
                          f"eventually earns less money per year.",
        "less_then_more": f"{A} earns less money per year than {B} at first but "
                          f"eventually earns more money per year.",
    }
    why = {
        "always_more": f"compares only the amounts invested, not what each account earns",
        "always_less": f"compares only the first year, and then assumes nothing changes",
        "more_then_less": f"has the compounded account falling behind a fixed amount, "
                          f"which compounding never does",
        "less_then_more": f"assumes the fixed amount is larger in the first year",
    }
    if first < fee:
        # a student has to see the crossing happen, so it must be inside the
        # lifetime of an account somebody would actually open
        years, earn = 1, first
        while earn <= fee and years <= 25:
            years += 1
            earn = pa * rate * (1 + rate) ** (years - 1)
        if earn <= fee:
            raise ItemError("the compounded account takes longer than a working life "
                            "to overtake the fixed amount")
    shape = "always_more" if first > fee else "less_then_more"
    key = S[shape]
    wrong = [Mis(why[s], S[s]) for s in S if s != shape]
    choices, reasons, letter = assemble_text(key, wrong, rng)
    table = [["", d["head"][0], d["head"][1]],
             [A, f"${pa:,}", f"{num_str(rate * 100)}% annual interest"],
             [B, f"${pb:,}", f"${num_str(fee)} per year"]]
    P = dict(kind="tvdata.invest_compare", pa=pa, rate=str(rate), pb=pb, fee=str(fee),
             a=A, b=B, texts=list(choices))
    return Item("tvdata.invest_compare", "comparing models", "hard", seed,
                f"{d['intro']} {d['ask']}", "mcq", E(0), letter,
                f"In the first year {A} earns ${num_str(first)} and {B} earns "
                f"${num_str(fee)}, and what {A} earns grows every year.",
                choices, reasons, list(choices), table=table, params=P)


# ------------------------------------------------- which table is not linear

def _pairs(xs, ys) -> str:
    """One two-row table, written out as the transcript writes the source's."""
    return (f"x = {', '.join(num_str(v) for v in xs)}; "
            f"y = {', '.join(num_str(v) for v in ys)}")


def nonlinear_table(rng: random.Random, seed: int, *, xs=None, ratio=None, start=None,
                    slopes=None, bases=None) -> Item:
    """Four small tables of x against y; in one the relationship is not linear."""
    xs = [q(v) for v in (xs if xs is not None else range(1, 5))]
    n = len(xs)
    if n < 4:
        raise ItemError("a table this short cannot show a pattern")
    if any(xs[i + 1] - xs[i] != xs[1] - xs[0] for i in range(n - 1)):
        raise ItemError("these tables step through x evenly")
    ratio = int(ratio if ratio is not None else rng.choice((2, 2, 3)))
    start = int(start if start is not None else rng.randint(2, 9))
    key_ys = [q(start) * ratio ** i for i in range(n)]
    if slopes is None:
        slopes = rng.sample([2, 3, 4, 5, 6, 7], 3)
    if bases is None:
        bases = [rng.randint(2, 9) for _ in range(3)]
    rows = []
    for s, b0 in zip(slopes, bases):
        rows.append([q(b0) + q(s) * i for i in range(n)])
    texts = [_pairs(xs, key_ys)] + [_pairs(xs, r) for r in rows]
    if len(set(texts)) != 4:
        raise ItemError("two of the four tables are the same")
    if ratio == 1 or any(all(r[i + 1] - r[i] == r[1] - r[0] for i in range(n - 1)) is False
                         for r in rows):
        raise ItemError("one of the three linear tables is not linear")
    key = texts[0]
    wrong = [Mis("the y-values here go up by the same amount each step, so this "
                 "relationship is linear", t) for t in texts[1:]]
    choices, reasons, letter = assemble_text(key, wrong, rng)
    shown = {t: r for t, r in zip(texts, [key_ys] + rows)}
    table = [[""] + [f"x = {num_str(v)}" for v in xs]]
    for i, t in enumerate(choices):
        table.append(["ABCD"[i]] + [num_str(v) for v in shown[t]])
    P = dict(kind="tvdata.nonlinear_table", xs=[str(v) for v in xs],
             texts=list(choices))
    return Item("tvdata.nonlinear_table", "choosing a model", "medium", seed,
                "In which of the following tables is the relationship between the "
                "values of x and their corresponding y-values nonlinear?", "mcq",
                E(0), letter,
                f"Those y-values multiply by {ratio} each step rather than adding a "
                f"fixed amount.", choices, reasons, list(choices), table=table,
                params=P)
