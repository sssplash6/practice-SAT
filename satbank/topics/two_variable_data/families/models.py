"""Choosing between models rather than reading one.

Four equations and one scatter; four sentences about an exponential against a
line; four tables and one that is not linear. In each the wrong options are
wrong for a reason a reader can check, so `option_check.py` evaluates all four
from what is printed and asserts that exactly one survives.
"""

from __future__ import annotations

import random
from fractions import Fraction as Q

from ....exact import E
